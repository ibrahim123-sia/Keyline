import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/**
 * `pnpm ai:prompts`: bundles features/ai/prompts/*.md into a TypeScript module, so the
 * prompts ship inside the Worker as plain strings (no file system at runtime, no bundler
 * loader). The .md files stay the source of truth, versioned in git (10 §6); a unit test
 * fails when the bundle is out of date.
 */

const DIR = resolve("src/features/ai/prompts");
const OUT = join(DIR, "bundle.generated.ts");

export function readPromptSources(dir = DIR): Record<string, string> {
  const out: Record<string, string> = {};
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".md"))
    .sort())
    out[file.slice(0, -3)] = readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n");
  return out;
}

function build(): void {
  const sources = readPromptSources();
  const names = Object.keys(sources);
  const body = [
    "// Generated by scripts/build-ai-prompts.ts from src/features/ai/prompts/*.md. Do not edit:",
    "// change the .md file and run `pnpm ai:prompts`.",
    "",
    `export const promptNames = ${JSON.stringify(names)} as const;`,
    "export type PromptName = (typeof promptNames)[number];",
    "",
    "export const promptSources: Record<PromptName, string> = {",
    ...names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(sources[n])},`),
    "};",
    "",
  ].join("\n");
  writeFileSync(OUT, body);
  spawnSync(process.execPath, [resolve("node_modules/prettier/bin/prettier.cjs"), "--write", OUT], {
    stdio: "inherit",
  });
  console.log(`[ai:prompts] ${names.length} prompts -> ${OUT}`);
}

const isMain = process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/build-ai-prompts.ts");
if (isMain) build();
