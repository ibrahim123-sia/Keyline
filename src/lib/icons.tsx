export const icons: Record<string, LucideIcon> = Object.assign({}, ...Object.values(iconGroups));
export const iconNames = Object.keys(icons);

/** Renders a stored icon name; unknown or empty names show a neutral dot. */
export function Icon({ name, className }: { name: string | null | undefined; className?: string }) {
  const Cmp = (name && icons[name]) || CircleDotIcon;
  return <Cmp className={className} aria-hidden />;
}
